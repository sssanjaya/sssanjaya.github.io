// Step 3 of the bake: turn Blender's floats into the files the site loads.
// usage: node tools/bake/pack.cjs <dir with scene.json and *.f32>
// Writes public/lightmap/<room|desk>-<l|r|m|a>.webp and src/data/lightmap.ts.
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "../..");
const sharp = require(path.join(root, "node_modules/sharp"));
(async () => {
  const dir = process.argv[2];
  const scene = JSON.parse(fs.readFileSync(path.join(dir, "scene.json"), "utf8"));
  const { size, pad } = scene;
  const SRC = ["l", "r", "m", "a"];
  const ATLAS = ["room", "desk"];
  const read = (a, s) => new Float32Array(fs.readFileSync(path.join(dir, `${ATLAS[a]}-${s}.f32`)).buffer.slice(0));
  // A light blur takes the last of the path tracer's grain out. Charts are
  // padded and their edges bled outward, so it does not reach a neighbour.
  const soften = (src) => {
    const w = [0.06, 0.24, 0.4, 0.24, 0.06];
    const tmp = new Float32Array(src.length);
    const out = new Float32Array(src.length);
    for (let y = 0; y < size; y++)
      for (let x = 0; x < size; x++) {
        let t = 0;
        for (let k = -2; k <= 2; k++) t += w[k + 2] * src[y * size + Math.min(size - 1, Math.max(0, x + k))];
        tmp[y * size + x] = t;
      }
    for (let y = 0; y < size; y++)
      for (let x = 0; x < size; x++) {
        let t = 0;
        for (let k = -2; k <= 2; k++) t += w[k + 2] * tmp[Math.min(size - 1, Math.max(0, y + k)) * size + x];
        out[y * size + x] = t;
      }
    return out;
  };
  // Before that, single texels far brighter than all their neighbours
  // ("fireflies") are pulled down to the median of the nine around them.
  const despeckle = (src) => {
    const out = Float32Array.from(src);
    const box = new Float32Array(9);
    for (let y = 1; y < size - 1; y++)
      for (let x = 1; x < size - 1; x++) {
        const i = y * size + x;
        let n = 0;
        for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) box[n++] = src[i + dy * size + dx];
        box.sort();
        if (src[i] > box[4] * 1.35 + 1e-6) out[i] = box[4];
      }
    return out;
  };
  const raw = ATLAS.map((_, a) => SRC.map((s) => read(a, s)));
  const maps = raw.map((set) => set.map((m) => soften(despeckle(despeckle(m)))));
  // "1.0" in a stored lightmap: nearly the brightest texel of that source.
  const k = SRC.map((_, s) => {
    const lit = [...maps[0][s], ...maps[1][s]].filter((v) => v > 0).sort((p, q) => p - q);
    return +(lit[Math.floor(lit.length * 0.9995)] || 1).toPrecision(4);
  });
  fs.mkdirSync(path.join(root, "public/lightmap"), { recursive: true });
  let bytes = 0;
  for (let a = 0; a < 2; a++)
    for (let s = 0; s < 4; s++) {
      const src = maps[a][s];
      const px = Buffer.alloc(size * size);
      // Square root, so the dark end keeps its steps; a little noise hides the rest.
      for (let i = 0; i < src.length; i++) px[i] = Math.max(0, Math.min(255, Math.sqrt(Math.min(src[i] / k[s], 1)) * 255 + ((i * 2654435761) % 1000) / 1000 - 0.5 + 0.5));
      const file = path.join(root, `public/lightmap/${ATLAS[a]}-${SRC[s]}.webp`);
      await sharp(px, { raw: { width: size, height: size, channels: 1 } }).webp({ quality: 88, effort: 6 }).toFile(file);
      bytes += fs.statSync(file).size;
    }
  // Keycaps and leaves: the mean light on each instance's own little chart.
  const inst = {};
  scene.each.forEach(([count, charts], i) => {
    if (!count) return;
    const rects = scene.rects[i];
    const a = scene.meshes.find((m) => m.i === i).atlas;
    const chart = charts === 6 ? 2 : 0; // a keycap's top; a leaf's whole skin
    const out = [];
    for (let n = 0; n < count; n++) {
      const [x, y, w, h] = rects.slice(4 * (n * charts + chart), 4 * (n * charts + chart) + 4);
      for (let s = 0; s < 4; s++) {
        let sum = 0;
        let c = 0;
        for (let yy = y + pad; yy < y + h - pad; yy++) for (let xx = x + pad; xx < x + w - pad; xx++, c++) sum += raw[a][s][yy * size + xx];
        out.push(+(sum / Math.max(1, c)).toPrecision(3));
      }
    }
    inst[i] = out;
  });
  const ts = `// Generated by tools/bake (see tools/bake/README.md). Do not edit by hand.
// Where each lit mesh's charts sit in the two lightmaps, how bright "1.0" is
// for each light, and the light reaching each keycap and leaf.
export const LM = {
  size: ${size},
  /** Light per unit of stored value, for the table lamp, desk lamp, monitor and window. */
  k: ${JSON.stringify(k)},
  /** x, y, w, h for every chart of every lit mesh, in scene order. */
  rects: ${JSON.stringify(scene.rects)} as number[][],
  /** Vertex count of each of those meshes, to catch a scene that has changed since the bake. */
  verts: ${JSON.stringify(scene.verts)} as number[],
  /** Light on each instance (four numbers each) of the instanced meshes, by scene order. */
  inst: ${JSON.stringify(inst)} as Record<number, number[]>,
};
`;
  fs.writeFileSync(path.join(root, "src/data/lightmap.ts"), ts);
  console.log("k", k, "| lightmaps", (bytes / 1024).toFixed(0), "KB | data", (ts.length / 1024).toFixed(0), "KB");
})();
